/* End-to-end de demostración cliente -> panel empresa en el MISMO dispositivo. */
'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
const admin=fs.readFileSync('app/src/main/assets/admin-demo.js','utf8');
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(x=>x[1]).filter(Boolean);
assert.equal(scripts.length,2);
function boot(storage=new Map()){
 const listeners={},root={innerHTML:'',addEventListener(t,fn){listeners[t]=fn;}},alerts=[];
 const store={getItem(k){return storage.get(k)??null},setItem(k,v){storage.set(k,v)},removeItem(k){storage.delete(k)}};
 const document={getElementById(){return root},querySelector(){return null}};
 const window={scrollTo(){},addEventListener(){}};
 const ctx={window,document,localStorage:store,navigator:{},location:{protocol:'file:',hostname:''},alert(x){alerts.push(x)},confirm(){return true},Intl,Date,structuredClone,console,URL,encodeURIComponent,Blob,setTimeout};
 vm.createContext(ctx);
 new vm.Script(scripts[0],{filename:'catalog.js'}).runInContext(ctx);
 new vm.Script(admin,{filename:'admin-demo.js'}).runInContext(ctx);
 new vm.Script(scripts[1],{filename:'client.js'}).runInContext(ctx);
 const click=(action,id)=>listeners.click({target:{closest(){return {disabled:false,dataset:{action,id}}}}});
 const inp=(field,value,type='text')=>listeners.input({target:{dataset:{field},value,type}});
 const change=(field,value,type='select-one')=>listeners.change({target:{dataset:{field},value,type,hasAttribute(){return false}}});
 return {window,root,click,inp,change,alerts,storage};
}
const d=boot();
const api=d.window.VILLABLANCA_DEMO;
assert.ok(api);
d.click('catalog');
d.click('selectService','aseo-hogar');
d.click('incExtra','planchado');
d.click('addCart');
d.click('catalog');
d.click('selectService','auto-city');
d.click('addCart');
assert.match(d.root.innerHTML,/Aseo hogar/);
assert.match(d.root.innerHTML,/auto/i);
d.change('client:commune','San Felipe');
d.inp('client:address','Calle de prueba 123');
d.inp('client:name','María Ejemplo');
d.inp('client:email','cliente-prueba@example.com');
d.inp('client:phone','912345678');
const future=new Date(Date.now()+6*86400000);
let date=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Santiago',year:'numeric',month:'2-digit',day:'2-digit'}).format(future);
while(d.window.VillablancaTest.isWeekend(date)||['2026-10-31','2026-11-01','2026-12-08','2026-12-25'].includes(date)){
 const [y,m,dd]=date.split('-').map(Number);
 date=new Date(Date.UTC(y,m-1,dd+1,12)).toISOString().slice(0,10);
}
d.change('client:day',date);
d.change('client:slot','Mañana · 08:00');
d.click('review');
assert.match(d.root.innerHTML,/REVISIÓN FINAL/);
d.click('goCheckout');
assert.match(d.root.innerHTML,/Confirmar pedido de PRUEBA · sin pagar/);
d.click('demoCheckoutConfirm');
assert.match(d.root.innerHTML,/Tu solicitud fue recibida exitosamente/);
assert.match(d.root.innerHTML,/la ficha de presentación/,'mensaje de confirmación y futura ficha');
const all=api.orders();
assert.equal(all.length,1,'una orden compartida entre vistas locales');
assert.equal(all[0].total,72600,'aseo 4 h + planchado 1 h + auto $25.000');
assert.equal(all[0].tasks.length,2,'trabajos independientes');
assert.equal(all[0].tasks[0].durationHours,5,'aseo + planchado en la misma tarea');
assert.equal(all[0].tasks[1].durationHours,null,'auto no agrega horas al aseo');
assert.equal(all[0].paymentStatus,'No cobrado · simulación');
d.click('demoAdmin');
assert.match(d.root.innerHTML,/Centro de/);
assert.match(d.root.innerHTML,/María Ejemplo/);
assert.match(d.root.innerHTML,/Por asignar/);
assert.ok(api.assign(all[0].id,'t1','w1').ok);
assert.ok(api.assign(all[0].id,'t2','w4').ok);
const order=api.orders()[0];
assert.equal(order.tasks[0].staffId,'w1');
assert.equal(order.tasks[1].staffId,'w4');
assert.ok(api.setStatus(order.id,'t1','En camino').ok);
assert.ok(api.receipt(order.id).includes('NO VÁLIDO COMO BOLETA ELECTRÓNICA'));
d.click('demoTab','agenda');
assert.match(d.root.innerHTML,/Agenda semanal/);
d.click('demoTab','personal');
assert.match(d.root.innerHTML,/Camila Torres/);
d.click('demoTab','logistica');
assert.match(d.root.innerHTML,/Organización de rutas/);
// Segundo dispositivo sin backend externo NO debe recibir pedidos: evitar falsas promesas.
const second=boot();
assert.equal(second.window.VILLABLANCA_DEMO.orders().length,0,'almacenamiento local, no sincronización remota');
assert.equal(d.alerts.length,0);
console.log('OK: pedido cliente -> panel local -> 2 asignaciones -> agenda; sin cobros y sin falsa sincronización.');
